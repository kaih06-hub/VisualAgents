"""Terminal output helpers (no dependencies; honours NO_COLOR)."""

from __future__ import annotations

import os
import sys
from typing import Any

_COLOR = sys.stderr.isatty() and not os.environ.get("NO_COLOR") and os.environ.get("TERM") != "dumb"


def _c(code: str, text: str) -> str:
    return f"\x1b[{code}m{text}\x1b[0m" if _COLOR else text


def bold(t: str) -> str:
    return _c("1", t)


def dim(t: str) -> str:
    return _c("2", t)


def accent(t: str) -> str:
    return _c("38;5;111", t)


def good(t: str) -> str:
    return _c("38;5;71", t)


def warn(t: str) -> str:
    return _c("38;5;214", t)


def bad(t: str) -> str:
    return _c("38;5;167", t)


def info(msg: str) -> None:
    """Status lines go to stderr so they never mix with a piped agent's stdout."""
    print(f"{accent('◆ visualagents')} {msg}", file=sys.stderr, flush=True)


def error(msg: str) -> None:
    print(f"{bad('✖ visualagents')} {msg}", file=sys.stderr, flush=True)


def banner(url: str, bp: dict[str, Any], extra: str = "") -> None:
    names = ", ".join(a["name"] for a in bp["agents"][:6]) + ("…" if len(bp["agents"]) > 6 else "")
    lines = [
        f"{bold('VisualAgents')} {dim('·')} {bp['project']} {dim('(' + bp['framework'] + ')')}",
        f"  {dim('dashboard')}  {accent(url)}",
        f"  {dim('agents')}     {len(bp['agents'])}: {names or '-'}",
    ]
    if extra:
        lines.append(f"  {dim(extra)}")
    print("\n".join(lines) + "\n", file=sys.stderr, flush=True)


def print_blueprint(bp: dict[str, Any], out=sys.stdout) -> None:
    by_id = {a["id"]: a for a in bp["agents"]}
    w = out.write
    w(f"\n{bold(bp['project'])}  {dim(bp['framework'])}  {dim('generated by ' + (bp.get('generated_by') or '?'))}\n")
    if bp["summary"]:
        w(f"{bp['summary']}\n")
    w(f"\n{bold('Agents')} ({len(bp['agents'])})\n")
    for a in bp["agents"]:
        loc = f"{a['file']}:{a['line']}" if a["file"] and a["line"] else a["file"]
        w(f"  {accent('●')} {bold(a['name'])}" + (f" {dim('—')} {a['role']}" if a["role"] else "") + "\n")
        if a["description"]:
            w(f"      {a['description']}\n")
        if a["tools"]:
            w(f"      {dim('tools:')} {', '.join(a['tools'])}\n")
        if loc:
            w(f"      {dim(loc)}\n")
    if bp["edges"]:
        w(f"\n{bold('Handoffs')}\n")
        for e in bp["edges"]:
            arrow = "⇢" if e["conditional"] else "→"
            label = f"  {dim(e['label'])}" if e["label"] else ""
            w(f"  {by_id[e['from']]['name']} {arrow} {by_id[e['to']]['name']}{label}\n")
    entry = ", ".join(by_id[i]["name"] for i in bp["entry"])
    exits = ", ".join(by_id[i]["name"] for i in bp["exits"])
    w(f"\n  {dim('entry:')} {entry or '-'}   {dim('final answer:')} {exits or '-'}\n")
    if bp["steps"]:
        w(f"\n{bold('Blueprint')}\n")
        for s in bp["steps"]:
            who = ", ".join(by_id[i]["name"] for i in s["agents"] if i in by_id)
            who = "" if who == s["title"] else who
            w(f"  {s['order']}. {bold(s['title'])}" + (f"  {dim(who)}" if who else "") + "\n")
            if s["description"]:
                w(f"     {dim(s['description'])}\n")
    w("\n")
